/**
 * Generates every prompt from data/network.json and writes:
 * - data/prompts.json: the prompt bank the game will read.
 * - docs/prompt-bank.md: a readable report, to review prompts by eye.
 *
 * Run with `bun run data:prompts`.
 */
import type { Network } from "../src/network.ts";
import { LIMITS, generatePromptBank, type PromptBank } from "../src/prompts/generate.ts";

const REGULAR_PROMPTS_PER_DAY = 6;

const network = (await Bun.file(new URL("../data/network.json", import.meta.url)).json()) as Network;
const bank = generatePromptBank(network);
const names = new Map(network.stations.map((station) => [station.id, station.name]));
const list = (ids: string[]) => ids.map((id) => names.get(id)).join(", ");

function report(bank: PromptBank): string {
  const spread = bank.prompts.filter((prompt) => prompt.spread).length;
  const byDifficulty = (difficulty: string) => bank.prompts.filter((prompt) => prompt.difficulty === difficulty).length;
  const out = [
    "# Prompt bank",
    "",
    `Generated by \`bun run data:prompts\` from \`data/network.json\`: ${network.stations.length} stations, with usage figures from ${network.usageYear}.`,
    "",
    "## Summary",
    "",
    `- **${bank.prompts.length} prompts** for the regular rounds: ${byDifficulty("easy")} easy (30+ answers), ${byDifficulty("medium")} medium (12–29) and ${byDifficulty("hard")} hard (${LIMITS.minAnswers}–11).`,
    `- **${spread}** of them have a good spread: at least one obvious answer and at least two quiet stations to hunt for.`,
    `- **${bank.interchange.length} Interchange prompts** for the double-points final round (two conditions at once, ${LIMITS.interchange.minAnswers}–${LIMITS.interchange.maxAnswers} answers).`,
    `- At ${REGULAR_PROMPTS_PER_DAY} regular prompts a day, that's **${Math.floor(bank.prompts.length / REGULAR_PROMPTS_PER_DAY)} days** before a regular prompt repeats.`,
    "",
    `A prompt is kept if it has ${LIMITS.minAnswers}–${LIMITS.maxAnswers} answers (some families have a lower maximum) and shares less than ${LIMITS.maxOverlap * 100}% of its answers with an earlier prompt.`,
    "Families of near-identical prompts, like walking distance or stops away, use a stricter limit within the family.",
    "Answers are listed busiest station first, which is roughly the order players will think of them.",
    "",
    "| Family | Generated | Kept | Too few answers | Too many | Repeats |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
    ...bank.families.map((f) => `| ${f.label} | ${f.candidates} | **${f.kept}** | ${f.tooFew} | ${f.tooMany} | ${f.repeats} |`),
    "",
  ];

  for (const family of bank.families) {
    const prompts = bank.prompts.filter((prompt) => prompt.family === family.id);
    if (prompts.length === 0) continue;
    out.push(`## ${family.label}`, "", "| Prompt | Answers | Likely answers | Deep cuts |", "| --- | ---: | --- | --- |");
    for (const prompt of prompts) {
      const deepCuts = prompt.answers.slice(Math.max(2, prompt.answers.length - 2));
      out.push(`| ${prompt.text} | ${prompt.answers.length} | ${list(prompt.answers.slice(0, 2))} | ${list(deepCuts)} |`);
    }
    out.push("");
  }

  const step = Math.max(1, Math.floor(bank.interchange.length / 40));
  out.push(
    "## Interchange prompts",
    "",
    `A sample of 40 out of ${bank.interchange.length}.`,
    "",
    "| Prompt | Answers |",
    "| --- | --- |",
    ...bank.interchange
      .filter((_, i) => i % step === 0)
      .slice(0, 40)
      .map((prompt) => `| ${prompt.text} | ${list(prompt.answers)} |`),
    "",
  );
  return out.join("\n");
}

await Bun.write(
  new URL("../data/prompts.json", import.meta.url),
  `${JSON.stringify({ limits: LIMITS, prompts: bank.prompts, interchange: bank.interchange }, null, 1)}\n`,
);
await Bun.write(new URL("../docs/prompt-bank.md", import.meta.url), report(bank));

console.table(bank.families.map(({ label, candidates, kept, tooFew, tooMany, repeats }) => ({ label, candidates, kept, tooFew, tooMany, repeats })));
console.log(
  `${bank.prompts.length} prompts (${bank.prompts.filter((p) => p.spread).length} with a good spread), ${bank.interchange.length} Interchange prompts`,
);
